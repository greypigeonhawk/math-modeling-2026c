"""抖动下的加车补偿：48/56 各加 1 辆 Z2，62 加 1~2 辆，看能否吸收 +1/+2 min 抖动"""
import q2_robust as R

base = dict(k1=8, k7=1, H=140)
CASES = [
    ('48架 k2=11', 32, 16, dict(k2=11, k8=7, k3=5, k4=5, k5=10, k6=10, P56=15, P34=10)),
    ('48架 k2=12', 32, 16, dict(k2=12, k8=8, k3=5, k4=5, k5=11, k6=11, P56=16, P34=10)),
    ('56架 k2=14', 32, 24, dict(k2=14, k8=9, k3=6, k4=6, k5=12, k6=12, P56=18, P34=12)),
    ('56架 k2=15', 32, 24, dict(k2=15, k8=10, k3=6, k4=6, k5=13, k6=13, P56=19, P34=12)),
    ('62架 k2=16', 32, 30, dict(k2=16, k8=11, k3=7, k4=7, k5=15, k6=15, P56=20, P34=14)),
    ('62架 k2=17', 32, 30, dict(k2=17, k8=12, k3=7, k4=7, k5=16, k6=16, P56=21, P34=14)),
]
for nm, nA, nB, c in CASES:
    for d in (0, 1, 2):
        st, val, _ = R.solve(nA, nB, dict(base, **c), delta=d)
        print(f'{nm}  delta={d}  {st} 完工={val}')
